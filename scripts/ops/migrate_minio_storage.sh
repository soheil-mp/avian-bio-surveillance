#!/usr/bin/env bash
# Switch MinIO between the default bind-mounted data directory and a Docker volume.

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "${script_dir}/../.." && pwd)"
override_file="${repo_root}/config/docker.local.env"
default_source_dir="${repo_root}/data/minio"
copy_image="${MINIO_STORAGE_COPY_IMAGE:-alpine:3.22}"

mode="check"
force_copy="false"
volume_name="minio-data"
source_dir="$default_source_dir"

usage() {
  cat <<'USAGE'
Usage: scripts/ops/migrate_minio_storage.sh [--check] [--apply] [--rollback] [--volume NAME] [--source DIR] [--force-copy]

Switch MinIO between the default repo bind mount and a Docker-managed named volume.

Modes:
  --check        Report the current MinIO storage configuration (default).
  --apply        Create/copy the named volume and enable MINIO_DATA_MOUNT in config/docker.local.env.
  --rollback     Remove the MINIO_DATA_MOUNT override so Compose falls back to the bind mount.

Options:
  --volume NAME  Target Docker volume name. Default: minio-data
  --source DIR   Source bind directory to copy from. Default: data/minio
  --force-copy   Replace existing contents in the target volume before copying.

This helper only prepares the storage cutover. Stop MinIO writers first, then restart
the MinIO service after --apply or --rollback so Compose picks up the new mount.
USAGE
}

while (($#)); do
  case "$1" in
    --check)
      mode="check"
      ;;
    --apply)
      mode="apply"
      ;;
    --rollback)
      mode="rollback"
      ;;
    --volume)
      shift
      volume_name="${1:-}"
      if [[ -z "$volume_name" ]]; then
        echo "--volume requires a value." >&2
        exit 2
      fi
      ;;
    --source)
      shift
      source_dir="${1:-}"
      if [[ -z "$source_dir" ]]; then
        echo "--source requires a value." >&2
        exit 2
      fi
      if [[ "$source_dir" != /* ]]; then
        source_dir="${repo_root}/${source_dir}"
      fi
      ;;
    --force-copy)
      force_copy="true"
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
  shift
done

target_mount() {
  echo "${volume_name}:/data"
}

default_mount() {
  echo "../../data/minio:/data"
}

read_override_mount() {
  if [[ ! -f "$override_file" ]]; then
    return 0
  fi
  awk -F= '/^MINIO_DATA_MOUNT=/{value=substr($0, index($0, "=") + 1)} END{print value}' "$override_file"
}

active_mount() {
  local override_mount
  override_mount="$(read_override_mount)"
  if [[ -n "${MINIO_DATA_MOUNT:-}" ]]; then
    echo "$MINIO_DATA_MOUNT"
  elif [[ -n "$override_mount" ]]; then
    echo "$override_mount"
  else
    default_mount
  fi
}

volume_exists() {
  docker volume inspect "$volume_name" >/dev/null 2>&1
}

volume_has_entries() {
  docker run --rm -v "${volume_name}:/data" "$copy_image" sh -lc 'find /data -mindepth 1 -print -quit | grep -q .'
}

source_has_entries() {
  [[ -d "$source_dir" ]] && find "$source_dir" -mindepth 1 -print -quit | grep -q .
}

print_status() {
  local mount
  local source_state="missing"
  local volume_state="missing"
  local mode_label="bind-mount"

  mount="$(active_mount)"
  if [[ -d "$source_dir" ]]; then
    source_state="present"
  fi
  if volume_exists; then
    volume_state="present"
  fi
  if [[ "$mount" == "$(target_mount)" ]]; then
    mode_label="named-volume"
  elif [[ "$mount" != "$(default_mount)" ]]; then
    mode_label="custom"
  fi

  cat <<STATUS
MinIO storage mode: ${mode_label}
Active MINIO_DATA_MOUNT: ${mount}
Override file: ${override_file} $( [[ -f "$override_file" ]] && echo "(present)" || echo "(absent)" )
Source bind directory: ${source_dir} (${source_state})
Target volume: ${volume_name} (${volume_state})
STATUS
}

ensure_volume() {
  docker volume create "$volume_name" >/dev/null
}

clear_volume() {
  docker run --rm -v "${volume_name}:/data" "$copy_image" sh -lc 'find /data -mindepth 1 -maxdepth 1 -exec rm -rf {} +'
}

copy_into_volume() {
  docker run --rm \
    -v "${volume_name}:/dest" \
    -v "${source_dir}:/source:ro" \
    "$copy_image" \
    sh -lc 'mkdir -p /dest && cp -a /source/. /dest/'
}

write_override() {
  local tmp_file
  tmp_file="$(mktemp)"
  if [[ -f "$override_file" ]]; then
    grep -v '^MINIO_DATA_MOUNT=' "$override_file" >"$tmp_file" || true
  else
    cat <<'HEADER' >"$tmp_file"
# Local Docker Compose overrides.
# Generated by scripts/ops/migrate_minio_storage.sh.
HEADER
  fi
  if [[ -s "$tmp_file" && "$(tail -c 1 "$tmp_file" 2>/dev/null || true)" != "" ]]; then
    printf '\n' >>"$tmp_file"
  fi
  printf 'MINIO_DATA_MOUNT=%s\n' "$(target_mount)" >>"$tmp_file"
  mv "$tmp_file" "$override_file"
}

remove_override() {
  local tmp_file
  if [[ ! -f "$override_file" ]]; then
    return 0
  fi
  tmp_file="$(mktemp)"
  grep -v '^MINIO_DATA_MOUNT=' "$override_file" >"$tmp_file" || true
  if [[ -s "$tmp_file" ]]; then
    mv "$tmp_file" "$override_file"
  else
    rm -f "$tmp_file" "$override_file"
  fi
}

apply_cutover() {
  if [[ ! -d "$source_dir" ]]; then
    echo "Source bind directory does not exist: $source_dir" >&2
    echo "Refusing to create an empty MinIO volume implicitly." >&2
    exit 1
  fi

  ensure_volume
  if volume_has_entries; then
    if [[ "$force_copy" != "true" ]]; then
      echo "Target volume ${volume_name} already contains data." >&2
      echo "Use --force-copy to replace its contents from ${source_dir}." >&2
      exit 1
    fi
    echo "Clearing existing contents from volume ${volume_name}."
    clear_volume
  fi

  if source_has_entries; then
    echo "Copying ${source_dir} into Docker volume ${volume_name}."
    copy_into_volume
  else
    echo "Source bind directory is empty; created empty Docker volume ${volume_name}."
  fi

  write_override
  echo "Enabled MINIO_DATA_MOUNT=$(target_mount) via config/docker.local.env."
  echo "Restart MinIO after writers are drained:"
  echo "  bash infrastructure/docker/compose.sh up -d --no-build --no-deps minio minio-init"
  echo "  bash scripts/ops/recover_minio.sh --check"
}

rollback_cutover() {
  remove_override
  echo "Removed MINIO_DATA_MOUNT override. Compose will fall back to $(default_mount)."
  echo "The Docker volume ${volume_name} was left intact. Restart MinIO to pick up the bind mount again."
}

main() {
  cd "$repo_root"
  case "$mode" in
    check)
      print_status
      ;;
    apply)
      apply_cutover
      print_status
      ;;
    rollback)
      rollback_cutover
      print_status
      ;;
  esac
}

main