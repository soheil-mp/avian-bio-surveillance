-- =============================================================================
-- Domain baseline DDL for modeling outputs.
-- Applied lexicographically by bootstrap/init_database.sh.
-- All DDL must be idempotent (CREATE IF NOT EXISTS, etc.).
-- =============================================================================

BEGIN;

-- =========================================================================
-- TABLE: modeling_runs_tbl (Derived regular table)
-- =========================================================================
-- Purpose: One persisted modeling/evaluation/tuning run envelope.
-- Grain  : One row per generated modeling run.
-- Notes  : Typed columns identify the run; JSONB payloads preserve full
--          configuration, stats, coverage, quality, and validation reports.
-- =========================================================================

CREATE TABLE IF NOT EXISTS modeling_runs_tbl (
    run_id TEXT PRIMARY KEY,
    run_kind TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'complete',
    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    parent_tuning_run_id TEXT,
    config JSONB NOT NULL DEFAULT '{}',
    stats JSONB NOT NULL DEFAULT '{}',
    source_coverage JSONB NOT NULL DEFAULT '{}',
    validation_report JSONB,
    quality_report JSONB,
    payload JSONB NOT NULL DEFAULT '{}',
    computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_mrt_kind_status_generated
    ON modeling_runs_tbl (run_kind, status, generated_at DESC);

CREATE INDEX IF NOT EXISTS idx_mrt_parent_tuning_run
    ON modeling_runs_tbl (parent_tuning_run_id)
    WHERE parent_tuning_run_id IS NOT null;

-- =========================================================================
-- TABLE: modeling_species_week_features_tbl
-- =========================================================================
-- Purpose: Weekly species/location feature rows generated by the modeling
--          phase. The payload contains every feature column emitted by Python.
-- =========================================================================

CREATE TABLE IF NOT EXISTS modeling_species_week_features_tbl (
    feature_row_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL,
    species_id TEXT,
    species_english TEXT,
    location_type TEXT,
    location_id TEXT,
    grid_cell_id TEXT,
    period_start DATE,
    period_end DATE,
    month_start DATE,
    total_detections BIGINT,
    active_days INTEGER,
    species_station_count INTEGER,
    community_total_detections BIGINT,
    community_active_days INTEGER,
    community_active_station_count INTEGER,
    payload JSONB NOT NULL DEFAULT '{}',
    computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_msf_run_species_period
    ON modeling_species_week_features_tbl (run_id, species_id, period_start DESC);

CREATE INDEX IF NOT EXISTS idx_msf_species_period
    ON modeling_species_week_features_tbl (species_id, period_start DESC)
    WHERE species_id IS NOT null;

CREATE INDEX IF NOT EXISTS idx_msf_payload_gin
    ON modeling_species_week_features_tbl USING gin (payload jsonb_path_ops);

-- =========================================================================
-- TABLE: modeling_species_week_scores_tbl
-- =========================================================================
-- Purpose: Weekly anomaly scores and attached weak-label/context columns.
--          top_detection_ids is typed because both frontend alert/explore paths
--          link detection-level views back to weekly model evidence.
-- =========================================================================

CREATE TABLE IF NOT EXISTS modeling_species_week_scores_tbl (
    score_row_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL,
    species_id TEXT,
    species_english TEXT,
    location_type TEXT,
    location_id TEXT,
    grid_cell_id TEXT,
    period_start DATE,
    period_end DATE,
    month_start DATE,
    alert_level TEXT,
    model_eligible BOOLEAN,
    model_fit_status TEXT,
    model_anomaly_score DOUBLE PRECISION,
    final_score DOUBLE PRECISION,
    population_anomaly_score DOUBLE PRECISION,
    population_drop_score DOUBLE PRECISION,
    population_spike_score DOUBLE PRECISION,
    embedding_anomaly_score DOUBLE PRECISION,
    embedding_drift_score DOUBLE PRECISION,
    embedding_outlier_share DOUBLE PRECISION,
    embedding_clip_count_scored INTEGER,
    top_detection_ids TEXT [] NOT NULL DEFAULT '{}',
    anomaly_streams TEXT [] NOT NULL DEFAULT '{}',
    payload JSONB NOT NULL DEFAULT '{}',
    computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_mss_run_species_period
    ON modeling_species_week_scores_tbl (run_id, species_id, period_start DESC);

CREATE INDEX IF NOT EXISTS idx_mss_run_location_period
    ON modeling_species_week_scores_tbl (run_id, location_id, period_start DESC);

CREATE INDEX IF NOT EXISTS idx_mss_run_alert_score
    ON modeling_species_week_scores_tbl (run_id, alert_level, final_score DESC);

-- Narrow run_id index so "which runs have score rows" (latestRunCte's
-- existence check) is served by an index-only scan instead of a full-table
-- seq scan — the latter dominated the homepage's cold first load.
CREATE INDEX IF NOT EXISTS idx_mss_run_id
    ON modeling_species_week_scores_tbl (run_id);

CREATE INDEX IF NOT EXISTS idx_mss_top_detection_ids_gin
    ON modeling_species_week_scores_tbl USING gin (top_detection_ids);

CREATE INDEX IF NOT EXISTS idx_mss_payload_gin
    ON modeling_species_week_scores_tbl USING gin (payload jsonb_path_ops);

-- =========================================================================
-- TABLE: modeling_embedding_clusters_tbl
-- =========================================================================
-- Purpose: Detection-level cluster assignments emitted by embedding drift.
-- =========================================================================

CREATE TABLE IF NOT EXISTS modeling_embedding_clusters_tbl (
    cluster_row_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL,
    detection_id TEXT,
    species_id TEXT,
    location_type TEXT,
    location_id TEXT,
    station_id TEXT,
    grid_cell_id TEXT,
    period_start DATE,
    period_end DATE,
    embedding_model TEXT,
    cluster_id TEXT,
    cluster_label TEXT,
    cluster_rank INTEGER,
    cluster_size INTEGER,
    cluster_count INTEGER,
    cluster_member_share DOUBLE PRECISION,
    cluster_centroid_distance DOUBLE PRECISION,
    cluster_distance_threshold DOUBLE PRECISION,
    cluster_quality TEXT,
    is_cluster_exemplar BOOLEAN,
    cluster_exemplar_detection_id TEXT,
    payload JSONB NOT NULL DEFAULT '{}',
    computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_mec_run_detection
    ON modeling_embedding_clusters_tbl (run_id, detection_id)
    WHERE detection_id IS NOT null;

CREATE INDEX IF NOT EXISTS idx_mec_run_period
    ON modeling_embedding_clusters_tbl (run_id, period_start DESC);

CREATE INDEX IF NOT EXISTS idx_mec_run_cluster
    ON modeling_embedding_clusters_tbl (run_id, cluster_id)
    WHERE cluster_id IS NOT null;

-- =========================================================================
-- Tuning leaderboards
-- =========================================================================

CREATE TABLE IF NOT EXISTS modeling_tuning_runs_tbl (
    tuning_run_id TEXT PRIMARY KEY,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sweep_mode TEXT,
    objective_weights JSONB NOT NULL DEFAULT '{}',
    negative_control_penalty DOUBLE PRECISION,
    top_k INTEGER,
    config_count INTEGER,
    best_config_label TEXT,
    best_objective DOUBLE PRECISION,
    best_config_overrides JSONB,
    payload JSONB NOT NULL DEFAULT '{}',
    computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_mtr_generated
    ON modeling_tuning_runs_tbl (generated_at DESC);

CREATE TABLE IF NOT EXISTS modeling_tuning_leaderboard_rows_tbl (
    tuning_leaderboard_row_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tuning_run_id TEXT NOT NULL,
    leaderboard_rank INTEGER,
    config_index INTEGER,
    config_label TEXT,
    objective DOUBLE PRECISION,
    overrides JSONB NOT NULL DEFAULT '{}',
    payload JSONB NOT NULL DEFAULT '{}',
    computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_mtlr_run_rank
    ON modeling_tuning_leaderboard_rows_tbl (tuning_run_id, leaderboard_rank)
    WHERE leaderboard_rank IS NOT null;

CREATE INDEX IF NOT EXISTS idx_mtlr_run_objective
    ON modeling_tuning_leaderboard_rows_tbl (tuning_run_id, objective DESC);

COMMENT ON TABLE modeling_runs_tbl IS
    'Run envelope for modeling, evaluation, import, and tuning candidate outputs.';
COMMENT ON TABLE modeling_species_week_scores_tbl IS
    'Weekly species/location anomaly scores with detection links and full JSONB payload.';
COMMENT ON TABLE modeling_species_week_features_tbl IS
    'Weekly species/location feature rows generated by the modeling phase.';
COMMENT ON TABLE modeling_embedding_clusters_tbl IS
    'Detection-level embedding cluster assignments emitted by modeling.';
COMMENT ON TABLE modeling_tuning_runs_tbl IS
    'Tuning sweep envelopes and objective metadata.';

COMMIT;
